// examples/app-interop/wallet-render: the typed data the wallet-render page asks a wallet to sign, built by the SDK's own
// grantTypedData / grantRevocationTypedData (@tapeapi/interop, experimental), so the page can never drift from the
// format: wallet-render.test.mjs fails when payloads.js differs from a fresh build.
//   node examples/app-interop/wallet-render/make-payloads.mjs        rewrites payloads.js
// Every name and address here is an EXAMPLE (12.7.tape and 13.7.tape are the local demo's names, not real services; the
// addresses are test fixtures made of repeated bytes). The visitor (`user`) is replaced in the page by the account the
// wallet connects: the statement names no address, so it does not change. Nothing here is ever sent anywhere.
// 钱包渲染测试页要签的类型数据，由 SDK 自己的 grantTypedData 生成，页面永远不会与格式漂移（payloads.js 与重新生成不一致时测试失败）。
// 名字与地址都是示例（12.7.tape、13.7.tape 是本地演示的名字，不是真实服务；地址是重复字节的夹具）。页面里 user 换成钱包连接的账户：
// statement 不含地址，所以不变。这里的任何东西都不发往任何地方。
import { writeFileSync } from 'node:fs'
import { CHAINS } from '@tapeapi/sdk'
import { makeGrant, grantTypedData, grantRevocationTypedData, grantHashOf } from '@tapeapi/interop'

export const CHAIN_ID = 56
export const HUB = CHAINS[CHAIN_ID].hub
const rep = (b) => '0x' + b.repeat(20)
/** the placeholder visitor; the page puts the connected account here / 占位访客，页面换成连接的账户 */
export const PLACEHOLDER_USER = rep('3a')
// 2026-11-02 08:00:00 UTC: a fixed time, so the file is the same on every build / 固定时间，每次生成都一样
const T = Date.UTC(2026, 10, 2, 8, 0, 0) / 1000
const base = {
  user: PLACEHOLDER_USER, caller: rep('a6'), callerName: '12.7.tape', callerHolder: rep('44'), callerKey: rep('4b'),
  audience: rep('5e'), audienceName: '13.7.tape', audienceHolder: rep('66'), now: T,
}
// the longest the format allows: 8 methods, 64-character names, 10,000 calls, 7 days / 格式允许的最长情形
const LONG = [
  'history', 'profile_settings_read', 'orders_list_by_visitor_with_pagination_and_status_filters',
  'messages_inbox_unread_count', 'favourites_list', 'notifications_preferences_read_for_this_visitor_only',
  'export_visitor_data_as_json', 'a_method_name_exactly_sixty_four_characters_long_to_test_display',
]

export function buildPayloads() {
  const grants = [
    { id: 'v1-en', title: 'v1 grant, English statement, 1 method, 5 calls, 1 hour', titleZh: 'v1 授权，英文首行，1 个方法，5 次，1 小时', message: makeGrant({ ...base, methods: ['history'], maxCalls: 5, nonce: '0x' + '01'.repeat(32), lang: 'en' }) },
    { id: 'v1-zh', title: 'v1 grant, Chinese statement, 1 method, 5 calls, 1 hour', titleZh: 'v1 授权，中文首行，1 个方法，5 次，1 小时', message: makeGrant({ ...base, methods: ['history'], maxCalls: 5, nonce: '0x' + '02'.repeat(32), lang: 'zh' }) },
    { id: 'v1-en-max', title: 'v1 grant, the longest: 8 methods (up to 64 characters), 10,000 calls, 7 days', titleZh: 'v1 授权，最长情形：8 个方法（名字最长 64 字符）、10,000 次、7 天', message: makeGrant({ ...base, methods: LONG, maxCalls: 10_000, lifeS: 7 * 86400, nonce: '0x' + '03'.repeat(32), lang: 'en' }) },
  ]
  const out = grants.map((g) => {
    const td = grantTypedData(CHAIN_ID, HUB, g.message)
    return { id: g.id, title: g.title, titleZh: g.titleZh, display: td.display, typedData: { domain: td.domain, types: td.types, primaryType: td.primaryType, message: td.message } }
  })
  // optional: a revocation of the three grants above (a bytes32[] array) / 可选：撤销上面三份授权（bytes32[] 数组）
  const rev = grantRevocationTypedData(CHAIN_ID, HUB, { user: PLACEHOLDER_USER, grantHashes: grants.map((g) => grantHashOf(CHAIN_ID, HUB, g.message)), revokedBefore: 0, issued: T })
  out.push({ id: 'revocation', title: 'Optional: a GrantRevocation of the three grants above (bytes32[] of 3)', titleZh: '可选：撤销上面三份授权（3 项的 bytes32[]）', display: null, typedData: rev })
  return out
}

export function payloadsSource() {
  return '// GENERATED by make-payloads.mjs from @tapeapi/interop (experimental). Do not edit: run `node make-payloads.mjs`.\n' +
    '// 由 make-payloads.mjs 生成，勿手改。Example names and fixture addresses only; nothing here is a real service.\n' +
    `window.WALLET_RENDER = ${JSON.stringify({ placeholderUser: PLACEHOLDER_USER, chainId: CHAIN_ID, payloads: buildPayloads() }, null, 2)}\n`
}

if (import.meta.url === new URL(process.argv[1], 'file:').href) {
  writeFileSync(new URL('./payloads.js', import.meta.url), payloadsSource())
  console.log('wrote payloads.js')
}
